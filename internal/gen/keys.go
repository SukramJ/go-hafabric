// The page's table of the keys a source fills, between KeysBegin and
// KeysEnd of Docs.
const (
	KeysBegin = "<!-- keys:begin (generated by internal/gen; do not edit) -->"
	KeysEnd   = "<!-- keys:end -->"
)

// Methods returns the method names the rows' commands deliver
// (model.Command.Method), sorted and unique.
func Methods(files []rowfile.File) []string {
	set := map[string]bool{}
	for _, f := range files {
		for i := range f.Rows {
			r := &f.Rows[i]
			for _, cs := range [][]rowfile.Cluster{r.Clusters, partClusters(r)} {
				for j := range cs {
					for k := range cs[j].Commands {
						if m := cs[j].Commands[k].Method; m != "" {
							set[m] = true
						}
					}
				}
			}
		}
	}
	return slices.Sorted(maps.Keys(set))
}

func partClusters(r *rowfile.Row) []rowfile.Cluster {
	var out []rowfile.Cluster
	for _, p := range r.Parts {
		out = append(out, p.Clusters...)
	}
	return out
}

// MethodConst is the Go constant name of a method: "Method" and the
// method's snake_case words in CamelCase ("preset_mode" → MethodPresetMode).
func MethodConst(m string) string {
	var b strings.Builder
	b.WriteString("Method")
	for w := range strings.SplitSeq(m, "_") {
		if w == "" {
			continue
		}
		b.WriteString(strings.ToUpper(w[:1]) + w[1:])
	}
	return b.String()
}

// methodsSource is the constant block of rows_gen.go.
func methodsSource(files []rowfile.File) string {
	ms := Methods(files)
	if len(ms) == 0 {
		return ""
	}
	var b strings.Builder
	b.WriteString("// The methods the rows' commands deliver as model.Command.Method: a\n")
	b.WriteString("// consumer's command handler compares against these, not against literals.\n")
	b.WriteString("const (\n")
	for _, m := range ms {
		fmt.Fprintf(&b, "\t%s = %q\n", MethodConst(m), m)
	}
	b.WriteString(")\n\n// methods are the method constants, sorted.\nvar methods = []string{")
	for i, m := range ms {
		if i > 0 {
			b.WriteString(", ")
		}
		b.WriteString(MethodConst(m))
	}
	b.WriteString("}\n\n")
	return b.String()
}

// Key is one state or extra key a platform's rows read.
type Key struct {
	Platform string
	// Name is "state", "state.<key>" or "extra.<key>".
	Name string
	// Rows are the rows that read it ("<platform>/<id>").
	Rows []string
	// Predicate says whether a row's predicate or feature condition reads
	// it (an extra key), Value whether a value mapping does.
	Predicate, Value bool
	// Default says whether the catalog states a default for an extra key
	// (go-ha-catalog data/mqtt.json, the platform's keys and its variants'
	// keys) — the value a row reads when the source leaves the key out.
	Default bool
}

// Keys returns the state and extra keys the rows of files read, by
// platform and name.
func Keys(files []rowfile.File) []Key {
	byName := map[string]*Key{}
	add := func(platform, row, name string, pred bool) {
		k := byName[platform+"\x00"+name]
		if k == nil {
			k = &Key{Platform: platform, Name: name}
			if x, ok := strings.CutPrefix(name, "extra."); ok {
				k.Default = catalogDefault(platform, x)
			}
			byName[platform+"\x00"+name] = k
		}
		if !slices.Contains(k.Rows, row) {
			k.Rows = append(k.Rows, row)
		}
		if pred {
			k.Predicate = true
		} else {
			k.Value = true
		}
	}
	for _, f := range files {
		for i := range f.Rows {
			r := &f.Rows[i]
			id := f.Platform + "/" + r.ID
			val := func(v *rowfile.Value) {
				if v == nil {
					return
				}
				if v.From == "state" || strings.HasPrefix(v.From, "state.") || strings.HasPrefix(v.From, "extra.") {
					add(f.Platform, id, v.From, false)
				}
				for _, s := range []string{v.Per, v.Times} {
					if strings.HasPrefix(s, "extra.") {
						add(f.Platform, id, s, false)
					}
				}
			}
			when := func(w *rowfile.When) {
				if w == nil {
					return
				}
				if w.Features != nil {
					add(f.Platform, id, "extra.supported_features", true)
				}
				for k := range w.Extra {
					add(f.Platform, id, "extra."+k, true)
				}
			}
			when(&r.When)
			for c := range r.Caveats {
				when(&r.Caveats[c].When)
			}
			if r.RideMeasurement != nil {
				val(&r.RideMeasurement.Value)
			}
			for _, cs := range [][]rowfile.Cluster{r.Clusters, partClusters(r)} {
				for j := range cs {
					c := &cs[j]
					for ft := range c.Features {
						when(c.Features[ft].When)
					}
					for _, as := range [][]rowfile.Attr{c.Initial, c.Attributes} {
						for a := range as {
							val(&as[a].Value)
							when(as[a].When)
							if len(as[a].StateIn) > 0 {
								add(f.Platform, id, "state", false)
							}
						}
					}
					for k := range c.Commands {
						cmd := &c.Commands[k]
						when(cmd.When)
						val(cmd.Raw)
						for _, n := range slices.Sorted(maps.Keys(cmd.JSON)) {
							v := cmd.JSON[n]
							val(&v)
						}
					}
				}
			}
		}
	}
	out := make([]Key, 0, len(byName))
	for _, k := range byName {
		out = append(out, *k)
	}
	slices.SortFunc(out, func(a, b Key) int {
		if c := strings.Compare(a.Platform, b.Platform); c != 0 {
			return c
		}
		return strings.Compare(a.Name, b.Name)
	})
	return out
}

// KeysTable returns the markdown table of Keys(files).
func KeysTable(files []rowfile.File) string {
	var b strings.Builder
	b.WriteString("| Platform | Key | Read by | Read as | Catalog default |\n| --- | --- | --- | --- | --- |\n")
	for _, k := range Keys(files) {
		var as []string
		if k.Predicate {
			as = append(as, "predicate")
		}
		if k.Value {
			as = append(as, "value")
		}
		def := "—"
		if strings.HasPrefix(k.Name, "extra.") {
			def = "no"
			if k.Default {
				def = "yes"
			}
		}
		rows := make([]string, len(k.Rows))
		for i, r := range k.Rows {
			rows[i] = "`" + r + "`"
		}
		fmt.Fprintf(&b, "| `%s` | `%s` | %s | %s | %s |\n", k.Platform, k.Name, strings.Join(rows, ", "), strings.Join(as, ", "), def)
	}
	return b.String()
}

// catalogDefault reports whether the catalog states a default for a
// platform key. It mirrors hamapping's catalogDefault (value.go), which
// the root package's tests hold equal to this one.
func catalogDefault(platform, key string) bool {
	mqtt, err := hacatalog.LoadMQTT()
	if err != nil {
		return false
	}
	schema, ok := mqtt.Platforms[platform]
	if !ok {
		return false
	}
	if k, ok := schema.Keys[key]; ok && k.Default != nil {
		return true
	}
	for _, v := range schema.Variants {
		if k, ok := v.Keys[key]; ok && k.Default != nil {
			return true
		}
	}
	return false
}
